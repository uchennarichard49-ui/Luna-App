let currentQuote = null;

let currentCategory = "All";

let favorites =
    JSON.parse(
        localStorage.getItem("lunaFavorites")
    ) || [];


// ==========================================
// ELEMENTS
// ==========================================

const quoteText =
    document.getElementById("quoteText");

const quoteAuthor =
    document.getElementById("quoteAuthor");

const quoteCategory =
    document.getElementById("quoteCategory");

const newQuoteButton =
    document.getElementById("newQuoteButton");

const favoriteButton =
    document.getElementById("favoriteButton");

const copyButton =
    document.getElementById("copyButton");

const shareButton =
    document.getElementById("shareButton");

const favoritesList =
    document.getElementById("favoritesList");

const favoriteCount =
    document.getElementById("favoriteCount");

const themeButton =
    document.getElementById("themeButton");

const message =
    document.getElementById("message");


// ==========================================
// MESSAGE
// ==========================================

function showMessage(text) {

    message.textContent = text;

    message.classList.add("show");

    setTimeout(() => {

        message.classList.remove("show");

    }, 1800);
}


// ==========================================
// GET AVAILABLE QUOTES
// ==========================================

function getAvailableQuotes() {

    if (currentCategory === "All") {

        return quotes;

    }

    return quotes.filter(
        quote =>
            quote.category === currentCategory
    );
}


// ==========================================
// SHOW RANDOM QUOTE
// ==========================================

function showRandomQuote() {

    const availableQuotes =
        getAvailableQuotes();

    if (availableQuotes.length === 0) {
        return;
    }

    let randomQuote;

    do {

        const randomIndex =
            Math.floor(
                Math.random() *
                availableQuotes.length
            );

        randomQuote =
            availableQuotes[randomIndex];

    } while (
        availableQuotes.length > 1 &&
        randomQuote === currentQuote
    );

    currentQuote = randomQuote;

    quoteText.textContent =
        currentQuote.text;

    quoteAuthor.textContent =
        "— " + currentQuote.author;

    quoteCategory.textContent =
        currentQuote.category;

    updateFavoriteButton();
}


// ==========================================
// CHECK FAVORITE
// ==========================================

function isFavorite(quote) {

    return favorites.some(
        item =>
            item.text === quote.text &&
            item.author === quote.author
    );

}


// ==========================================
// UPDATE FAVORITE BUTTON
// ==========================================

function updateFavoriteButton() {

    if (!currentQuote) {
        return;
    }

    if (isFavorite(currentQuote)) {

        favoriteButton.textContent =
            "❤️ Favorited";

    } else {

        favoriteButton.textContent =
            "♡ Favorite";

    }

}


// ==========================================
// TOGGLE FAVORITE
// ==========================================

function toggleFavorite() {

    if (!currentQuote) {
        return;
    }

    const index =
        favorites.findIndex(
            item =>
                item.text === currentQuote.text &&
                item.author === currentQuote.author
        );

    if (index !== -1) {

        favorites.splice(index, 1);

        showMessage(
            "Removed from favorites"
        );

    } else {

        favorites.push(currentQuote);

        showMessage(
            "❤️ Added to favorites"
        );

    }

    localStorage.setItem(
        "lunaFavorites",
        JSON.stringify(favorites)
    );

    updateFavoriteButton();

    displayFavorites();
}


// ==========================================
// DISPLAY FAVORITES
// ==========================================

function displayFavorites() {

    favoriteCount.textContent =
        favorites.length;

    if (favorites.length === 0) {

        favoritesList.innerHTML = `
            <p class="empty-message">
                Your favorite quotes will appear here.
            </p>
        `;

        return;
    }

    favoritesList.innerHTML = "";

    favorites.forEach(
        (quote, index) => {

            const item =
                document.createElement("div");

            item.className =
                "favorite-item";

            item.innerHTML = `

                <p>
                    “${escapeHTML(quote.text)}”
                </p>

                <p class="favorite-author">
                    — ${escapeHTML(quote.author)}
                    · ${escapeHTML(quote.category)}
                </p>

                <button
                    class="remove-favorite"
                    data-index="${index}">
                    Remove
                </button>

            `;

            favoritesList.appendChild(item);

        }
    );


    document
        .querySelectorAll(".remove-favorite")
        .forEach(button => {

            button.addEventListener(
                "click",
                function () {

                    const index =
                        Number(
                            this.dataset.index
                        );

                    favorites.splice(
                        index,
                        1
                    );

                    localStorage.setItem(
                        "lunaFavorites",
                        JSON.stringify(
                            favorites
                        )
                    );

                    displayFavorites();

                    updateFavoriteButton();

                    showMessage(
                        "Removed from favorites"
                    );

                }
            );

        });

}


// ==========================================
// ESCAPE HTML
// ==========================================

function escapeHTML(text) {

    const div =
        document.createElement("div");

    div.textContent = text;

    return div.innerHTML;
}


// ==========================================
// COPY QUOTE
// ==========================================

async function copyQuote() {

    if (!currentQuote) {
        return;
    }

    const text =
        `"${currentQuote.text}" — ${currentQuote.author}`;

    try {

        await navigator.clipboard.writeText(
            text
        );

        showMessage(
            "📋 Quote copied!"
        );

    } catch (error) {

        showMessage(
            "Copy failed"
        );

    }

}


// ==========================================
// SHARE QUOTE
// ==========================================

async function shareQuote() {

    if (!currentQuote) {
        return;
    }

    const text =
        `"${currentQuote.text}" — ${currentQuote.author}`;

    if (navigator.share) {

        try {

            await navigator.share({

                title: "LUNA Quotes",

                text: text

            });

        } catch (error) {

            // Sharing cancelled.

        }

    } else {

        await copyQuote();

        showMessage(
            "Quote copied!"
        );

    }

}


// ==========================================
// CATEGORY BUTTONS
// ==========================================

document
    .querySelectorAll(".category")
    .forEach(button => {

        button.addEventListener(
            "click",
            function () {

                document
                    .querySelectorAll(".category")
                    .forEach(btn => {

                        btn.classList.remove(
                            "active"
                        );

                    });

                this.classList.add(
                    "active"
                );

                currentCategory =
                    this.dataset.category;

                showRandomQuote();

            }
        );

    });


// ==========================================
// DARK MODE
// ==========================================

function loadTheme() {

    const savedTheme =
        localStorage.getItem(
            "lunaTheme"
        );

    if (savedTheme === "dark") {

        document.body.classList.add(
            "dark"
        );

        themeButton.textContent =
            "☀️";

    } else {

        document.body.classList.remove(
            "dark"
        );

        themeButton.textContent =
            "🌙";

    }

}


themeButton.addEventListener(
    "click",
    () => {

        document.body.classList.toggle(
            "dark"
        );

        const isDark =
            document.body.classList.contains(
                "dark"
            );

        localStorage.setItem(
            "lunaTheme",
            isDark
                ? "dark"
                : "light"
        );

        themeButton.textContent =
            isDark
                ? "☀️"
                : "🌙";

    }
);


// ==========================================
// BUTTON EVENTS
// ==========================================

newQuoteButton.addEventListener(
    "click",
    showRandomQuote
);

favoriteButton.addEventListener(
    "click",
    toggleFavorite
);

copyButton.addEventListener(
    "click",
    copyQuote
);

shareButton.addEventListener(
    "click",
    shareQuote
);


// ==========================================
// START LUNA
// ==========================================

loadTheme();

displayFavorites();

showRandomQuote();